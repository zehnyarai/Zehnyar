#!/usr/bin/env bash
# Release signing ONLY. Missing stable material is a hard stop, never a new random key.
set +x
set -euo pipefail
umask 077
python3 tools/signing_identity.py
: "${ANDROID_HOME:?Android SDK is required}"
export PESTINO_ANDROID_KEY_PASSWORD="${PESTINO_ANDROID_KEY_PASSWORD:-$PESTINO_ANDROID_STORE_PASSWORD}"
temporary="$(mktemp -d "${RUNNER_TEMP:-${TMPDIR:-/tmp}}/pestino-signing.XXXXXX")"
trap 'rm -rf -- "$temporary"' EXIT
export PESTINO_PRIVATE_KEY_PATH="$temporary/release.p12"
python3 - <<'PY'
import base64, os
from pathlib import Path
try:
    encoded = os.environ['PESTINO_ANDROID_KEYSTORE_B64']
    if len(encoded) > 180000:
        raise ValueError()
    data = base64.b64decode(encoded, validate=True)
    if not data:
        raise ValueError()
    path = Path(os.environ['PESTINO_PRIVATE_KEY_PATH'])
    path.write_bytes(data)
    path.chmod(0o600)
except (ValueError, KeyError):
    raise SystemExit('Signing blocked: invalid keystore secret; no replacement key was generated.')
PY
unset PESTINO_ANDROID_KEYSTORE_B64
alias="$(python3 -c 'from tools.signing_identity import load_identity; print(load_identity()["key_alias"])')"
if ! keytool -exportcert -keystore "$PESTINO_PRIVATE_KEY_PATH" -alias "$alias" \
  -storepass:env PESTINO_ANDROID_STORE_PASSWORD -file "$temporary/certificate.der" >/dev/null 2>&1; then
  echo 'Signing blocked: existing keystore could not be opened. No new identity was generated.' >&2
  exit 1
fi
python3 tools/signing_identity.py --certificate "$temporary/certificate.der"
mkdir -p apk-output
version="$(python3 -c 'import json; print(json.load(open("package.json"))["version"])')"
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo 'Invalid release version' >&2; exit 1; }
apk="apk-output/Pestino-$version.apk"
unsigned=android/app/build/outputs/apk/release/app-release-unsigned.apk
"$ANDROID_HOME/build-tools/36.0.0/zipalign" -P 16 -f 4 "$unsigned" "$temporary/aligned.apk"
"$ANDROID_HOME/build-tools/36.0.0/apksigner" sign \
  --ks "$PESTINO_PRIVATE_KEY_PATH" --ks-key-alias "$alias" \
  --ks-pass env:PESTINO_ANDROID_STORE_PASSWORD --key-pass env:PESTINO_ANDROID_KEY_PASSWORD \
  --v1-signing-enabled true --v2-signing-enabled true --v3-signing-enabled true \
  --v4-signing-enabled false --out "$apk" "$temporary/aligned.apk"
"$ANDROID_HOME/build-tools/36.0.0/apksigner" verify --verbose --print-certs "$apk" > "$temporary/verification.txt"
python3 tools/signing_identity.py --verify-apk-info "$temporary/verification.txt" --record-apk "$apk"
echo 'Release signed with the pinned, stable certificate; no key was generated by the build.'
