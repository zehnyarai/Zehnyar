def pick_theme(v, phrase):
    hay = phrase + " " + " ".join(
        e.get("text", "")[:500] for f in ("modern", "context", "notes")
        for e in v.get(f, []) if isinstance(e, dict))
    best, score = None, 0
    for name, kws, crit, research, bible in THEMES:
        s = sum(1 for k in kws if k in hay)
        if s > score:
            best, score = (name, kws, crit, research, bible), s
    return best if best else ("عام", [], GENERIC[1], GENERIC[2], None)


