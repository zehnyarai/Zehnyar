def source_url(source_id: str, v: int) -> str:
    if source_id in {"ar_tabari_qurancom", "ar_ibn_kathir_qurancom", "ar_jalalayn_qurancom"}:
        return shared.SOURCE_META[source_id]["url"].format(verse=v)
    if source_id == "ar_tusi_tibyan":
        page = TUSI_GROUPS[v][0]
        return f"https://www.greattafsirs.com/Tafsir_Library.aspx?FromMainTafsir=1&MadhabNo=4&TafsirNo=39&SoraNo=4&AyahNo={page}&LanguageID=1"
    if source_id == "ar_fayd_safi":
        page = FAYD_GROUPS[v][0]
        return f"https://www.greattafsirs.com/Tafsir_Library.aspx?FromMainTafsir=1&MadhabNo=4&TafsirNo=41&SoraNo=4&AyahNo={page}&LanguageID=1"
    if source_id == "ar_qe_arabic_moyassar":
        return "https://quranenc.com/en/browse/arabic_moyassar"
    if source_id == "en_tafheem_ul_quran":
        return TAFHEEM_GROUPS[v][0]
    raise KeyError(source_id)


def source_cite(source_id: str, v: int) -> str:
    return {
        "ar_tabari_qurancom": tabari,
        "ar_ibn_kathir_qurancom": ibn,
        "ar_jalalayn_qurancom": jalalayn,
        "ar_tusi_tibyan": tusi,
        "ar_fayd_safi": fayd,
        "ar_qe_arabic_moyassar": moyassar,
        "en_tafheem_ul_quran": tafheem,
    }[source_id](v)


def source_evidence(source_id: str, v: int) -> str:
    if source_id in {"ar_tabari_qurancom", "ar_ibn_kathir_qurancom", "ar_jalalayn_qurancom"}:
        return f"صفحهٔ آیه‌محورِ منبع برای نساء ۴:{fa_num(v)} بررسی شد؛ خلاصه به شرحِ دریافت‌شده و همان آیه محدود است."
    if source_id == "ar_tusi_tibyan":
        page, scope = TUSI_GROUPS[v]
        return f"مسیرِ آیهٔ {fa_num(page)} در GreatTafsirs بررسی شد؛ دامنهٔ واقعیِ شرحِ طوسی نساء {scope} است."
    if source_id == "ar_fayd_safi":
        page, scope = FAYD_GROUPS[v]
        if v == 168:
            return f"صفحهٔ گروهیِ فیض برای نساء {scope} بررسی شد؛ متنِ دریافت‌شده شرحِ مستقلِ ۴:۱۶۸ را نشان نمی‌دهد."
        return f"مسیرِ آیهٔ {fa_num(page)} در GreatTafsirs بررسی شد؛ دامنهٔ واقعیِ شرحِ گروهیِ فیض نساء {scope} است."
    if source_id == "ar_qe_arabic_moyassar":
        return f"متنِ محلیِ QuranEnc برای نساء ۴:{fa_num(v)} از نسخهٔ 1.0.0 بررسی شد؛ خلاصه نقلِ لفظی نیست."
    if source_id == "en_tafheem_ul_quran":
        _, scope = TAFHEEM_GROUPS[v]
        return f"صفحهٔ گروهیِ واقعیِ {scope} بررسی شد؛ جایگاهِ یادداشت: {TAFHEEM_NOTES[v]}؛ دامنهٔ گروه حفظ شده است."
