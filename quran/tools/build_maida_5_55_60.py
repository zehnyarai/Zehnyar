def source_evidence(source_id: str, verse: int) -> str:
    if source_id in SUNNI:
        if source_id == "ar_tabari_qurancom" and verse == 60:
            return "صفحهٔ مستقیمِ ۵:۶۰ و هر سه قطعهٔ اعلام‌شده خوانده شد؛ قرائتِ مختارِ طبری از گزارش‌هایِ قرائت جدا نگه داشته شده است."
        return f"صفحهٔ مستقیمِ آیه‌محورِ منبع برای مائده ۵:{fa_num(verse)} بررسی شد؛ خلاصه به بدنهٔ همان شرح محدود است."
    if source_id == "ar_tusi_tibyan":
        page, scope = TUSI_GROUPS[verse]
        return f"صفحهٔ GreatTafsirs با AyahNo={page} بررسی شد؛ دامنهٔ شرحِ مستقیمِ طوسی مائده {scope} است؛ قطعه‌هایِ اعلام‌شدهٔ ۵:{fa_num(verse)} خوانده شدند."
    if source_id == "ar_fayd_safi":
        page, scope = FAYD_GROUPS[verse]
        return f"صفحهٔ GreatTafsirs با AyahNo={page} بررسی شد؛ دامنهٔ واقعیِ شرحِ فیض مائده {scope} است؛ فقط موضعِ ۵:{fa_num(verse)} خلاصه شده است."
    if source_id == QURANENC:
        return f"متنِ محلیِ قرآن‌انک برای مائده ۵:{fa_num(verse)} از نسخهٔ 1.0.0 بررسی شد؛ خلاصه نقلِ لفظی نیست."
    if source_id == TAFHEEM:
        _, scope, note = TAFHEEM_GROUPS[verse]
        chunk = "قطعهٔ ۰" if verse in {58, 60} else "قطعه‌هایِ ۰–۵"
        return f"صفحهٔ انتخابیِ تفہیم القرآن با دامنهٔ {scope} بررسی شد؛ {chunk} شاملِ موضعِ ۵:{fa_num(verse)} و شاهدِ {note} است؛ چاپ و صفحهٔ کتاب احراز نشده."
    if source_id == WASIT:
        route = WASIT_ROUTES[verse]
        return (
            f"صفحهٔ Quran.com با مسیرِ ۵:{fa_num(route)} بررسی شد؛ عنوان و بدنهٔ عربیِ دریافت‌شده هر دو شرحِ ۵:{fa_num(verse)} را نشان می‌دهند. "
            "ناهماهنگیِ مسیرهایِ ۵:۴۳–۴۹ در این بازه مشاهده نشد."
        )
    raise KeyError(source_id)


def source_item(source_id: str, verse: int, text: str) -> dict:
    return {
        "text": text,
        "cite": source_cite(source_id, verse),
        "kind": "source-summary",
        "language": "fa",
        "sourceId": source_id,
        "sourceUrl": source_url(source_id, verse),
        "evidence": source_evidence(source_id, verse),
        "limit": shared.SOURCE_LIMIT,
        "tradition": shared.SOURCE_TRADITIONS.get(source_id, "اهل‌سنت"),
    }


def build_entry(verse: int, record: dict) -> dict:
    entry = {"title": record["title"]}
    for field in ("notes", "context"):
        entry[field] = [editorial_item(row, verse, field) for row in record[field]]
    entry["classical"] = [source_item(source_id, verse, text) for source_id, text in record["classical"].items()]
    entry["modern"] = [source_item(source_id, verse, text) for source_id, text in record["modern_sources"].items()]
    entry["modern"].extend(model_item(model, text, verse) for model, text in record["models"].items())
    for field in ("critical", "research"):
        entry[field] = [editorial_item(row, verse, field) for row in record[field]]
    entry["status"] = shared.STATUS
    entry["standard"] = 2
    return entry


