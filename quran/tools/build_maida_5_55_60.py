def source_url(source_id: str, verse: int) -> str:
    if source_id in SUNNI:
        slug = {
            "ar_tabari_qurancom": "ar-tafsir-al-tabari",
            "ar_ibn_kathir_qurancom": "ar-tafsir-ibn-kathir",
            "ar_jalalayn_qurancom": "ar-tafsir-jalalayn",
        }[source_id]
        return f"https://quran.com/al-maidah/{verse}/tafsirs/{slug}"
    if source_id == "ar_tusi_tibyan":
        page, _ = TUSI_GROUPS[verse]
        return greattafsirs_url(39, page)
    if source_id == "ar_fayd_safi":
        page, _ = FAYD_GROUPS[verse]
        return greattafsirs_url(41, page)
    if source_id == QURANENC:
        return "https://quranenc.com/en/browse/arabic_moyassar"
    if source_id == TAFHEEM:
        return TAFHEEM_GROUPS[verse][0]
    if source_id == WASIT:
        return f"https://quran.com/al-maidah/{WASIT_ROUTES[verse]}/tafsirs/ar-tafsir-al-wasit"
    raise KeyError(source_id)


