def validate_data() -> None:
    assert set(DATA) == set(VERSES)
    for v, entry in DATA.items():
        assert all(len(entry[field]) == 5 for field in ("notes", "context", "critical", "research")), v
        assert len(entry["classical"]) == 5 and set(entry["classical"]) == SUNNI_CORE | SHIA_CORE, v
        assert len(entry["modern_sources"]) == 2
        assert set(entry["modern_sources"]) == {"ar_qe_arabic_moyassar", "en_tafheem_ul_quran"}
        assert set(entry["models"]) == {"izutsu", "fillmore", "cognitive"}


