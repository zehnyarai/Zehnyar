def tabari_url(v: int) -> str:
    return f"https://quran.com/an-nisa/{v}/tafsirs/ar-tafsir-al-tabari"


def tusi_url(page: int) -> str:
    return f"https://www.greattafsirs.com/Tafsir_Library.aspx?FromMainTafsir=1&MadhabNo=4&TafsirNo=39&SoraNo=4&AyahNo={page}&LanguageID=1"


def fayd_url(page: int) -> str:
    return f"https://www.greattafsirs.com/Tafsir_Library.aspx?FromMainTafsir=1&MadhabNo=4&TafsirNo=41&SoraNo=4&AyahNo={page}&LanguageID=1"


def source_url(source_id: str, v: int) -> str:
    if source_id == "ar_tabari_qurancom":
        return tabari_url(v)
    if source_id == "ar_ibn_kathir_qurancom":
        return shared.SOURCE_META[source_id]["url"].format(verse=v)
    if source_id == "ar_jalalayn_qurancom":
        return shared.SOURCE_META[source_id]["url"].format(verse=v)
    if source_id == "ar_tusi_tibyan":
        return tusi_url(TUSI_GROUPS[v][0])
    if source_id == "ar_fayd_safi":
        return fayd_url(FAYD_GROUPS[v][0])
    if source_id == "ar_qe_arabic_moyassar":
        return "https://quranenc.com/en/browse/arabic_moyassar"
    if source_id == "en_tafheem_ul_quran":
        return TAFHEEM_GROUPS[v][0]
    raise KeyError(source_id)


def source_cite(source_id: str, v: int) -> str:
    return {
        "ar_tabari_qurancom": tabari_cite,
        "ar_ibn_kathir_qurancom": ibn_cite,
        "ar_jalalayn_qurancom": jalalayn_cite,
        "ar_tusi_tibyan": tusi_cite,
        "ar_fayd_safi": fayd_cite,
        "ar_qe_arabic_moyassar": moyassar_cite,
        "en_tafheem_ul_quran": tafheem_cite,
    }[source_id](v)


def source_evidence(source_id: str, v: int) -> str:
    if source_id == "ar_tabari_qurancom":
        return f"صفحهٔ مستقیمِ Quran.com برای نساء ۴:{fa_num(v)} بررسی شد؛ خلاصه به شرحِ آیه و یادداشت‌های همان صفحه محدود است."
    if source_id == "ar_ibn_kathir_qurancom":
        return f"صفحهٔ آیه‌محورِ ابن‌کثیر برای نساء ۴:{fa_num(v)} در Quran.com بررسی شد؛ چاپ و صفحهٔ کتاب احراز نشده است."
    if source_id == "ar_jalalayn_qurancom":
        return f"صفحهٔ مستقیمِ جلالین برای نساء ۴:{fa_num(v)} در Quran.com بررسی شد؛ گزارش به همان شرح محدود است."
    if source_id == "ar_tusi_tibyan":
        page, scope = TUSI_GROUPS[v]
        return f"مسیرِ آیهٔ {fa_num(page)} در GreatTafsirs بررسی شد؛ متنِ موجود شرحِ نساء {scope} را دربرمی‌گیرد."
    if source_id == "ar_fayd_safi":
        page, scope = FAYD_GROUPS[v]
        return f"مسیرِ آیهٔ {fa_num(page)} در GreatTafsirs بررسی شد؛ دامنهٔ واقعیِ شرحِ گروهی نساء {scope} است."
    if source_id == "ar_qe_arabic_moyassar":
        return f"متنِ محلیِ QuranEnc برای نساء ۴:{fa_num(v)} از نسخهٔ 1.0.0 بررسی شد؛ خلاصه نقلِ لفظی نیست."
    if source_id == "en_tafheem_ul_quran":
        _url, scope = TAFHEEM_GROUPS[v]
        return f"صفحهٔ رسمیِ گروهیِ {scope} بررسی شد؛ جایگاهِ یادداشت‌ها: {TAFHEEM_NOTES[v]}؛ دامنهٔ گروه حفظ شده است."
    raise KeyError(source_id)


def source_item(source_id: str, v: int, text: str) -> dict:
    return {
        "text": text,
        "cite": source_cite(source_id, v),
        "kind": "source-summary",
        "language": "fa",
        "sourceId": source_id,
        "sourceUrl": source_url(source_id, v),
        "evidence": source_evidence(source_id, v),
        "limit": shared.SOURCE_LIMIT,
        "tradition": shared.SOURCE_TRADITIONS[source_id],
    }


def build_entry(v: int, data: dict) -> dict:
    entry = {"title": data["title"]}
    for field in ("notes", "context"):
        entry[field] = [shared.editorial_item(item, v, field) for item in data[field]]
    entry["classical"] = [source_item(sid, v, text) for sid, text in data["classical"].items()]
    entry["modern"] = [source_item(sid, v, text) for sid, text in data["modern_sources"].items()]
    entry["modern"].extend(shared.model_item(model, text, v) for model, text in data["models"].items())
    for field in ("critical", "research"):
        entry[field] = [shared.editorial_item(item, v, field) for item in data[field]]
    entry["status"] = shared.STATUS
    entry["standard"] = 2
    return entry


