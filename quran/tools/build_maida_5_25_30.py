def source_evidence(source_id: str, v: int) -> str:
    if source_id in SUNNI:
        return f"صفحهٔ آیه‌محورِ منبع برای مائده ۵:{fa_num(v)} بررسی شد؛ خلاصه به شرحِ دریافت‌شده و همان آیه محدود است."
    if source_id == "ar_tusi_tibyan":
        page, scope = TUSI_GROUPS[v]
        return f"صفحهٔ مستقیمِ GreatTafsirs با پارامترِ AyahNo={page} بررسی شد؛ شرح به مائده {scope} محدود است."
    if source_id == "ar_fayd_safi":
        page, scope = FAYD_GROUPS[v]
        return f"صفحهٔ GreatTafsirs با پارامترِ AyahNo={page} بررسی شد؛ دامنهٔ واقعیِ شرحِ گروهیِ فیض مائده {scope} است."
    if source_id == "ar_qe_arabic_moyassar":
        return f"متنِ محلیِ QuranEnc برای مائده ۵:{fa_num(v)} از نسخهٔ 1.0.0 بررسی شد؛ خلاصه نقلِ لفظی نیست."
    if source_id == "en_tafheem_ul_quran":
        _, scope, note = TAFHEEM_GROUPS[v]
        if "بی‌یادداشت" in note:
            return f"صفحهٔ گروهیِ واقعیِ {scope} بررسی شد؛ برای ۵:{fa_num(v)} شرحِ مستقل ندارد و این خلاصه تنها بر ترجمهٔ مستقیم متکی است."
        return f"صفحهٔ گروهیِ واقعیِ {scope} بررسی شد؛ جایگاهِ شرح: {note}؛ شمارهٔ یادداشت به همان آیه نسبت داده شده است."
    if source_id == "ar_wasit_qurancom":
        return f"صفحهٔ آیه‌محورِ التفسير الوسيط برای مائده ۵:{fa_num(v)} مستقیم بررسی شد؛ خلاصه به متنِ همان آیه محدود است."
    raise KeyError(source_id)


def source_item(source_id: str, v: int, text: str) -> dict:
    return {
        "text": text,
        "cite": source_cite(source_id, v),
        "kind": "source-summary",
        "language": "fa",
        "sourceId": source_id,
        "sourceUrl": source_url(source_id, v),
        "evidence": source_evidence(source_id, v),
        "limit": shared.SOURCE_LIMIT,
        "tradition": shared.SOURCE_TRADITIONS.get(source_id, "اهل‌سنت"),
    }


def build_entry(v: int, record: dict) -> dict:
    entry = {"title": record["title"]}
    for field in ("notes", "context"):
        entry[field] = [editorial_item(row, v, field) for row in record[field]]
    entry["classical"] = [source_item(sid, v, text) for sid, text in record["classical"].items()]
    entry["modern"] = [source_item(sid, v, text) for sid, text in record["modern_sources"].items()]
    entry["modern"].extend(model_item(model, text, v) for model, text in record["models"].items())
    for field in ("critical", "research"):
        entry[field] = [editorial_item(row, v, field) for row in record[field]]
    entry["status"] = shared.STATUS
    entry["standard"] = 2
    return entry


