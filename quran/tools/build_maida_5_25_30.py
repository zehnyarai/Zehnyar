def editorial_item(record: dict | str, verse: int, field: str) -> dict:
    if isinstance(record, str):
        text = record
        cite = (
            f"قرآن، مائده ۵:{fa_num(verse)}؛ نقدِ تحریری با مقابلهٔ منابعِ یادشده."
            if field == "critical"
            else f"پرسشِ پژوهشی دربارهٔ مائده ۵:{fa_num(verse)}؛ منابعِ مقایسه در متنِ بند مشخص شده‌اند."
        )
    else:
        text, cite = record["text"], record["cite"]
    return {
        "text": text,
        "cite": cite,
        "kind": shared.FIELD_KIND[field],
        "language": "fa",
        "evidence": f"شاهدِ متنی: مائده ۵:{fa_num(verse)}؛ بند با ارجاعِ ثبت‌شده و در دامنهٔ همان آیه سنجیده شود.",
        "limit": shared.EDITORIAL_LIMIT,
    }


