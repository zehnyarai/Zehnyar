def fa_num(value: int) -> str:
    return str(value).translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))


def item(text: str, cite: str) -> dict:
    return {"text": text, "cite": cite}


def quran(v: int, span: str | None = None) -> str:
    return f"قرآن، مائده {span or '۵:' + fa_num(v)}؛ متنِ عربی و ترجمهٔ فولادوند/Tanzil در پیکرهٔ برنامه."


def tabari(v: int) -> str:
    return f"طبری، ۳۱۰ق، *جامع البيان عن تأويل آي القرآن*، ذیلِ مائده ۵:{fa_num(v)}؛ صفحهٔ آیه‌محورِ Quran.com."


def ibn(v: int) -> str:
    return f"ابن‌کثیر، ۷۷۴ق، *تفسير القرآن العظيم*، ذیلِ مائده ۵:{fa_num(v)}؛ صفحهٔ آیه‌محورِ Quran.com؛ چاپ و صفحهٔ کتاب احراز نشده."


