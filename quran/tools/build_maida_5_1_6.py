def validate_data() -> None:
    assert set(DATA) == set(VERSES)
    for v, record in DATA.items():
        assert all(len(record[field]) == 5 for field in ("notes", "context", "critical", "research")), v
        assert set(record["classical"]) == SUNNI | SHIA, v
        assert set(record["modern_sources"]) == MODERN, v
        assert set(record["models"]) == MODELS, v
        for field in ("notes", "context", "critical", "research"):
            assert all(len(row["text"].split()) >= 14 and row["cite"] for row in record[field]), (v, field)


