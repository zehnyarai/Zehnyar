def nisa_coverage(verses: dict) -> tuple[int, str]:
    present = {int(key.split(":")[1]) for key in verses if key.startswith("4:")}
    end = 0
    while end + 1 in present:
        end += 1
    if end >= 176:
        return end, "نساء ۴:۱–۱۷۶ اکنون پوشش دارد"
    next_verse = str(end + 1).translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))
    return end, f"نساء ۴:{next_verse}–۱۷۶ هنوز پوشش ندارد"


