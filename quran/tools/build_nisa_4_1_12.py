def build_entry(verse: int, record: dict) -> dict:
    entry = {"title": record["title"]}
    for field in ("notes", "context"):
        entry[field] = [editorial_item(item, verse, field) for item in record[field]]
    entry["classical"] = [
        source_item(source_id, verse, text)
        for source_id, text in record["classical"].items()
    ]
    entry["modern"] = [
        source_item(source_id, verse, text)
        for source_id, text in record["modern_sources"].items()
    ]
    entry["modern"].extend(
        model_item(model, text, verse) for model, text in record["models"].items()
    )
    for field in ("critical", "research"):
        entry[field] = [editorial_item(item, verse, field) for item in record[field]]
    entry["status"] = STATUS
    entry["standard"] = 2
    return entry


