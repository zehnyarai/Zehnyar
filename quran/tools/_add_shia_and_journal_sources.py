def add(verse_id: str, field: str, items: list[tuple[str, str]]) -> None:
    record = VERSES[verse_id]
    for text, cite in items:
        assert all(existing["text"] != text for existing in record[field]), (verse_id, field)
        record[field].append({"text": text, "cite": cite})


