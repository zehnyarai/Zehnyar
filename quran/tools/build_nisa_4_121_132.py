def fa_num(value: int) -> str:
    return str(value).translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))


def editorial(text: str, cite: str) -> dict:
    return {"text": text, "cite": cite}


def quran_cite(scope: str) -> str:
    return f"قرآن، نساء {scope}؛ متن عربی و ترجمهٔ فولادوند/Tanzil در پیکرهٔ برنامه."


