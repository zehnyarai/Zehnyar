def build_entry(verse: int, record: dict) -> dict:
    entry = {"title": record["title"]}
    for field in ("notes", "context"):
        entry[field] = [editorial_item(text, verse, field) for text in record[field]]
    classical_readings = dict(record["classical"])
    classical_readings.update(SHIA_CLASSICAL_READINGS[verse])
    entry["classical"] = [
        source_item(source_id, verse, text)
        for source_id, text in classical_readings.items()
    ]
    entry["modern"] = [
        source_item(source_id, verse, text)
        for source_id, text in record["modern"].items()
    ]
    if "coverage" in record:
        entry["modern"].append(coverage_item(verse, record["coverage"]))
    for model, text in record["models"].items():
        entry["modern"].append(model_item(model, text, verse))
    entry["critical"] = [editorial_item(text, verse, "critical") for text in record["critical"]]
    entry["research"] = [editorial_item(text, verse, "research") for text in record["research"]]
    entry["status"] = STATUS
    entry["standard"] = 2
    return entry


