def tabari_url(v: int) -> str:
    return f"https://quran.com/an-nisa/{v}/tafsirs/ar-tafsir-al-tabari"


def source_url(source_id: str, v: int) -> str:
    if source_id == "ar_tabari_qurancom":
        return tabari_url(v)
    if source_id in {"ar_ibn_kathir_qurancom", "ar_jalalayn_qurancom"}:
        return shared.SOURCE_META[source_id]["url"].format(verse=v)
    if source_id == "ar_tusi_tibyan":
        page = TUSI_GROUPS[v][0]
        return f"https://www.greattafsirs.com/Tafsir_Library.aspx?FromMainTafsir=1&MadhabNo=4&TafsirNo=39&SoraNo=4&AyahNo={page}&LanguageID=1"
    if source_id == "ar_fayd_safi":
        page = FAYD_GROUPS[v][0]
        return f"https://www.greattafsirs.com/Tafsir_Library.aspx?FromMainTafsir=1&MadhabNo=4&TafsirNo=41&SoraNo=4&AyahNo={page}&LanguageID=1"
    if source_id == "ar_qe_arabic_moyassar":
        return "https://quranenc.com/en/browse/arabic_moyassar"
    if source_id == "en_tafheem_ul_quran":
        return TAFHEEM_GROUPS[v][0]
    raise KeyError(source_id)


def source_cite(source_id: str, v: int) -> str:
    return {
        "ar_tabari_qurancom": tabari_cite,
        "ar_ibn_kathir_qurancom": ibn_cite,
        "ar_jalalayn_qurancom": jalalayn_cite,
        "ar_tusi_tibyan": tusi_cite,
        "ar_fayd_safi": fayd_cite,
        "ar_qe_arabic_moyassar": moyassar_cite,
        "en_tafheem_ul_quran": tafheem_cite,
    }[source_id](v)


