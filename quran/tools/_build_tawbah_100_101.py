def tr(n: int) -> str:
    return TR["9"][n - 1]["text"]


def rec_base(text, cite):
    return {"text": text, "cite": cite}


def rec_entry(text, cite, evidence, limit, kind="analysis"):
    return {"kind": kind, "text": text, "cite": cite, "evidence": evidence, "limit": limit}


def field(entries, note, follow):
    return {"status": "partial", "coverage": {"completed": len(entries), "required": 5},
            "sourceCoverageNote": note, "followUp": follow, "entries": entries}


def build(n: int, *, title: str, review: str, notes: list, context: list, classical: list,
          modern: list, critical: list, research: list, ext: dict) -> dict:
    record = {
        "tier": "core",
        "sourcePolicyVersion": 2,
        "title": title,
        "reviewStatus": review,
        "coverageNote": ("این رکورد در سطحِ core است: شش فیلدِ پایه هر یک سه مدخل و ده فیلدِ افزوده یک یا دو "
                         "مدخل دارند؛ سطحِ full به پنج مدخلِ مقابله‌شده در هر فیلد نیاز دارد و ادعای "
                         "کامل‌بودن نمی‌شود."),
        "fieldCoverageStatus": ("شش فیلدِ پایه سه‌مدخلی‌اند و فیلدهایِ افزوده یک یا دو مدخلی؛ هر جا منبعِ "
                                "مقابله‌شده داده‌ای نداشته، همان کمبود با status و یادداشت ثبت شده است."),
        "notes": notes,
        "context": context,
        "classical": classical,
        "modern": modern,
        "critical": critical,
        "research": research,
        "extendedFields": {},
    }
    for fid in FIELDS:
        value = ext[fid]
        items = value if isinstance(value, list) else [value]
        entries = [rec_entry(text, cite, evidence, limit, kind) for text, evidence, limit, cite, kind in items]
        record["extendedFields"][fid] = field(
            entries,
            f"برای توبه ۹:{n} در فیلدِ {fid} {len(entries)} مدخل ثبت شده است؛ رسیدن به پوششِ پنج‌مدخلی به "
            f"مقابلهٔ منابعِ تخصصیِ همین فیلد نیاز دارد.",
            "منابعِ تخصصیِ این فیلد مقابله شوند و مدخل‌ها به پنج برسد؛ در نبودِ شاهد، ادعا ساخته نشود.",
        )
    record["sourceMix"] = collect(record)
    return record


