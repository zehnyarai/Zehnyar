def fa_num(value: int) -> str:
    return str(value).translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))


def group_cite(author: str, book: str, group: str, site: str) -> str:
    return f"{author}، *{book}*، شرحِ گروهیِ نساء {group}؛ {site}؛ چاپ/صفحهٔ کتاب احراز نشده."


def tusi_cite(verse: int) -> str:
    return (
        f"طوسی، ۴۶۰ق، *التبيان الجامع لعلوم القرآن*، ذیلِ نساء ۴:{fa_num(verse)}؛ "
        "GreatTafsirs، صفحهٔ مستقیم؛ چاپ/صفحهٔ کتاب احراز نشده."
    )


