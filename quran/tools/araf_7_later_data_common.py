"""Shared record generator for al-A'raf 7:101–206 draft batches."""
from __future__ import annotations

from anam_6_91_140_data import (
    TABARI, IBN, QURTUBI, TUSI, FAYD, QURANENC, WASIT,
    T, I, Q, U, F, M, W, point, verse,
)

QURTUBI_GAPS = {"7:104", "7:106", "7:122", "7:125", "7:147", "7:151", "7:174"}


def fa_num(value: int) -> str:
    return str(value).translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))


def make_record(ayah: int, spec: tuple) -> dict:
    title, focus, lexemes, issue, limit, claims, model_terms = spec
    tabari, ibn, qurtubi, tusi, fayd = claims
    key = f"7:{ayah}"
    qurtubi_gap = key in QURTUBI_GAPS
    if qurtubi_gap:
        qurtubi = (
            f"بدنهٔ آرشیوشدهٔ قرطبی برایِ اعراف ۷:{fa_num(ayah)} صریحاً «لا يوجد تفسير لهذه الأية» دارد؛ "
            "این خلأِ همان نسخه است و نبودِ شرح در کلِ اثر یا نسخه‌هایِ دیگر را ثابت نمی‌کند."
        )

    notes = [
        point(
            f"در اعراف ۷:{fa_num(ayah)}، {focus}؛ واژگانِ «{lexemes[0]}» و «{lexemes[-1]}» این خوانش را به عبارتِ خودِ آیه پیوند می‌دهند.",
            T, M,
        ),
        point(
            f"مناقشهٔ این موضع چنین است: {issue}؛ گزارشِ طبری و ابن‌کثیر را با واژه‌هایِ آیه مقابله کنید و یک قول را اجماع نخوانید.",
            T, I,
        ) if not qurtubi_gap else point(
            f"در اعراف ۷:{fa_num(ayah)} بدنهٔ ذخیره‌شدهٔ قرطبی تفسیر ندارد؛ این خلأ را با گزارشِ طبری و ابن‌کثیر اشتباه نگیرید.",
            T, I, Q,
        ),
        point(
            f"طوسی ذیلِ این موضع {tusi}؛ این بازنویسی گزارشِ متنِ اوست و باید از نتیجه‌گیریِ تحریریِ پرونده جدا بماند.",
            U,
        ),
        point(
            f"فیض در دامنهٔ نشان‌دارِ این موضع {fayd}؛ نشانِ گروهی دامنهٔ متن است و به‌تنهایی شرحِ مستقل یا صفحهٔ چاپی نمی‌سازد.",
            F,
        ),
        point(
            f"در کنارِ {focus}، طنطاوی سیاقِ روایت را توضیح می‌دهد و التفسير الميسر مضمون را فشرده می‌کند؛ هیچ‌یک جایِ شاهدِ عربی را نمی‌گیرد.",
            W, M,
        ),
    ]

    classical = {
        TABARI: (
            f"طبری ذیلِ «{title}» {tabari}؛ این بازنویسی به مدخلِ آیه‌محورِ آرشیوشده محدود است "
            "و نقلِ لفظی یا اجماعِ تفسیری نیست."
        ),
        IBN: (
            f"ابن‌کثیر ذیلِ «{title}» {ibn}؛ گزارشِ روایی و ترجیحِ او به خودِ مفسر منسوب است "
            "و در صورتِ اختلاف جدا می‌ماند."
        ),
        QURTUBI: qurtubi if qurtubi_gap else (
            f"قرطبی ذیلِ «{title}» {qurtubi}؛ این خلاصه فقط بدنهٔ موجود در آرشیو را بازمی‌گوید "
            "و اطلاعاتِ چاپ یا صفحه نمی‌افزاید."
        ),
        TUSI: (
            f"طوسی در *التبيان* ذیلِ «{title}» {tusi}؛ دامنهٔ مستقیم یا گروهی در ارجاع ثبت شده "
            "و این بازنویسی نقلِ لفظی نیست."
        ),
        FAYD: (
            f"فیض در *الصافي* ذیلِ «{title}» {fayd}؛ دامنهٔ واقعیِ نشانِ نسخه جدا ثبت شده "
            "و اطلاعاتِ نشرِ احرازنشده ساخته نشده است."
        ),
    }
    moyassar = (
        f"التفسير الميسر در ذیلِ «{title}» مضمونِ آیه را چنین می‌فهماند: {focus}؛ "
        "این بازنویسی از متنِ محلیِ آیه‌به‌آیه است و نقلِ لفظی نیست."
    )
    wasit = (
        f"طنطاوی در *التفسير الوسيط* ذیلِ اعراف ۷:{fa_num(ayah)}، {focus}؛ "
        f"او «{lexemes[0]}» را در پیوند با سیاقِ سوره توضیح می‌دهد و این خلاصه به همان مدخل محدود است."
    )

    critical = [
        point(
            f"حدِّ ادعا در این آیه چنین است: {limit}؛ از {focus} به‌تنهایی نباید روایتِ تاریخی یا قاعده‌ای فراتر از سیاق ساخت.",
            T, W,
        ),
        point(
            f"در واژهٔ «{lexemes[0]}»، {issue}؛ اختلافِ ثبت‌شده را آشکار نگه دارید و یک ترجمهٔ فارسی را یگانه معنایِ ممکن معرفی نکنید.",
            U,
        ) if qurtubi_gap else point(
            f"در واژهٔ «{lexemes[0]}»، {issue}؛ اختلافِ ثبت‌شده را آشکار نگه دارید و یک ترجمهٔ فارسی را یگانه معنایِ ممکن معرفی نکنید.",
            Q, U,
        ),
        point(
            f"گزارشِ ابن‌کثیر چنین است: {ibn}؛ این دیدگاهِ مفسر است و برایِ اثباتِ رخداد یا مصداقِ تاریخی به شاهدِ مستقل نیاز دارد.",
            I,
        ),
        point(
            f"فیض در متنِ نشان‌گذاری‌شده {fayd}؛ دامنهٔ گروهی/مستقیم باید از ادعایِ صفحه، چاپ یا نسخهٔ کامل جدا بماند.",
            F,
        ),
        point(
            f"خوانشِ معاصر دربارهٔ «{lexemes[-1]}» با {focus} پیوند می‌خورد؛ آن را تحلیلِ همین آیه نگه دارید، نه داوری دربارهٔ اشخاص یا جوامعِ امروز.",
            M, W,
        ),
    ]

    research = [
        point(
            f"طبری و ابن‌کثیر دربارهٔ «{lexemes[0]}» چه شاهدی می‌آورند و اختلافِ «{issue}» با عبارتِ عربیِ اعراف ۷:{fa_num(ayah)} چگونه سنجیده می‌شود؟",
            T, I,
        ),
        point(
            f"قرطبی و طوسی ذیلِ «{title}» و در پیوند با «{lexemes[1]}» چه تفاوتی دارند؛ آیا کانونِ اختلاف «{issue}» نحوی، لغوی یا روایی است؟",
            Q, U,
        ) if not qurtubi_gap else point(
            f"بدنهٔ آرشیوشدهٔ قرطبی در اعراف ۷:{fa_num(ayah)} تفسیر ندارد؛ چه نسخهٔ دیگری برایِ بررسیِ دیدگاهِ قرطبی لازم است؟",
            Q,
        ),
        point(
            f"فیض ذیلِ اعراف ۷:{fa_num(ayah)} چه روایت یا نکته‌ای را برایِ «{lexemes[-1]}» نقل می‌کند و کدام بخش هنوز نیازمندِ مقابله است؟",
            F,
        ),
        point(
            f"التفسير الميسر و طنطاوی در خواندنِ «{title}» کدام عنصرِ سیاق را برجسته می‌کنند و چه تفاوتی با گزارشِ طبری باقی می‌ماند؟",
            M, W, T,
        ),
        point(
            f"با توجه به اینکه {limit}، چه شاهدِ متنی یا نسخه‌شناختی برایِ ترجیحِ یک تفسیرِ اعراف ۷:{fa_num(ayah)} لازم است و چه چیزی فعلاً نامعلوم می‌ماند؟",
            U, F,
        ),
    ]
    return verse(title, notes, classical, moyassar, wasit, model_terms, critical, research)
