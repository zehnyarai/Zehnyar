def main() -> None:
    registry = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    dossier = json.loads(DOSSIER_PATH.read_text(encoding="utf-8"))
    for verse, data in DATA.items():
        if not any("فولادوند/Tanzil" in item["cite"] for item in data["notes"]):
            data["notes"][0]["cite"] += f"؛ متنِ قرآن و ترجمهٔ فولادوند/Tanzil، نساء ۴:{fa_num(verse)}."
        dossier["verses"][f"4:{verse}"] = build_entry(verse, data)

    dossier["batches"] = [batch for batch in dossier["batches"] if batch["id"] != BATCH_ID]
    nisa_end, nisa_gap = shared.nisa_coverage(dossier["verses"])
    dossier["batches"].append({
        "id": BATCH_ID,
        "title": "بستهٔ چهلم: نساء ۴:۹۷–۱۰۸؛ هجرت، نمازِ خوف و منعِ خیانت",
        "range": "4:97–108", "count": 12,
        "status": (
            "۱۲ پروندهٔ آیه‌محور با دست‌کم پنج بندِ مستند در هر یک از شش فیلد؛ "
            "در هر آیه پنج تفسیرِ کهن (سه اهل‌سنت و دو امامیه)، دو شرحِ معاصر و سه کاربستِ معناشناختی آمده است؛ "
            f"پیش‌نویسِ نیازمندِ بازبینیِ تخصصی؛ {nisa_gap}."
        ),
    })
    dossier["batches"].sort(key=lambda batch: int(batch["id"].split("-")[1]))
    for batch in dossier["batches"]:
        if batch.get("range", "").startswith("4:") and "؛ نساء ۴:" in batch.get("status", ""):
            prefix = batch["status"].split("؛ نساء ۴:", 1)[0]
            batch["status"] = f"{prefix}؛ {nisa_gap}."
    end_fa = fa_num(nisa_end)
    dossier["notice"] = (
        "این پرونده‌ها پیش‌نویس‌های تحریریِ منبع‌محورند و بازبینیِ تخصصی را پشت سر نگذاشته‌اند. "
        f"نساء در این checkout بازهٔ ۴:۱–{end_fa} را پوشش می‌دهد؛ {nisa_gap}. "
        "بسته‌های یونس بازه‌های ۱۰:۴۹–۶۰، ۱۰:۶۱–۷۲ و ۱۰:۷۳–۸۴ را پوشش می‌دهند؛ برای ۱۰:۱–۴۸ پرونده‌ای ساخته نشده است. "
        "این داده‌ها ادعای تکمیلِ هیچ‌یک از دو سوره یا کل قرآن را نمی‌کنند. خلاصه‌ها نقلِ لفظی نیستند؛ اختلافِ اقوال و دامنهٔ واقعیِ صفحاتِ گروهی جدا ثبت شده است."
    )

    method = re.sub(r"نساء ۴:\d+–۱۷۶ هنوز(?: در این checkout)? پوشش ندارد", nisa_gap, dossier["editorialMethod"])
    addition = (
        " در بستهٔ نساء ۴:۹۷–۱۰۸، عذرِ واقعی و هجرت در ۴:۹۷–۱۰۰، اختلافِ معنای «مراغماً» و گزارش‌های متنوعِ مهاجرِ درگذشته ثبت شده است. "
        "اختلافِ فقهیِ قصر و نمازِ خوف در ۴:۱۰۱–۱۰۲، معناهای «موقوتاً» در ۴:۱۰۳ و سیاقِ جنگیِ ۴:۱۰۴ جدا شده‌اند؛ "
        "روایت‌های بنی‌ابیرق و بحثِ قصد یا فعل در ۴:۱۰۵–۱۰۸ به مفسران نسبت داده شده و یکسان‌سازی نشده‌اند. "
        "سه صفحهٔ رسمیِ مودودی، صفحاتِ مستقیم و گروهیِ طوسی و فیض و صفحاتِ آیه‌محورِ جلالین مقابله شدند. "
        "برای ۴:۱۰۸، متنِ طبری در صفحهٔ ۴:۱۰۷ ادامه دارد و ناهماهنگیِ صفحهٔ ۴:۱۰۸ شفاف ثبت شده است. "
        f"این دوازده پرونده پیش‌نویس و نیازمندِ داوریِ تخصصی‌اند؛ {nisa_gap}."
    )
    if "در بستهٔ نساء ۴:۹۷–۱۰۸" not in method:
        method += addition
    dossier["editorialMethod"] = method
    DOSSIER_PATH.write_text(json.dumps(dossier, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    catalog = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    catalog["collections"] = [collection for collection in catalog["collections"] if collection["id"] != COLLECTION_ID]
    catalog["collections"].append(build_catalog(registry))
    catalog["version"] = max(int(catalog.get("version", 0)), 16)
    CATALOG_PATH.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Added {len(DATA)} dossiers; total={len(dossier['verses'])}; batch=4:97–108")


if __name__ == "__main__":
    main()
