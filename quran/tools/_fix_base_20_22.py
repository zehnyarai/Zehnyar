def de_short(t):
    """نامِ کوتاهِ اثر («میزان/نمونه/مختصر») در آغازِ جمله یا پس از «و» ← وصفِ بی‌نام."""
    t = re.sub(r"(?<![A-Za-z])nem\s+", "", t)  # برچسبِ داخلیِ منبع
