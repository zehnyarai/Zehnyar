def source_url(source_id: str, v: int) -> str:
    if source_id in SUNNI:
        slug = {
            "ar_tabari_qurancom": "ar-tafsir-al-tabari",
            "ar_ibn_kathir_qurancom": "ar-tafsir-ibn-kathir",
            "ar_jalalayn_qurancom": "ar-tafsir-jalalayn",
        }[source_id]
        return f"https://quran.com/al-maidah/{v}/tafsirs/{slug}"
    if source_id == "ar_tusi_tibyan":
        return f"https://www.greattafsirs.com/Tafsir_Library.aspx?FromMainTafsir=1&MadhabNo=4&TafsirNo=39&SoraNo=5&AyahNo={v}&LanguageID=1"
    if source_id == "ar_fayd_safi":
        page, _ = FAYD_GROUPS[v]
        return f"https://www.greattafsirs.com/Tafsir_Library.aspx?FromMainTafsir=1&MadhabNo=4&TafsirNo=41&SoraNo=5&AyahNo={page}&LanguageID=1"
    if source_id == "ar_qe_arabic_moyassar":
        return "https://quranenc.com/en/browse/arabic_moyassar"
    if source_id == "en_tafheem_ul_quran":
        return TAFHEEM_GROUPS[v][0]
    if source_id == "ar_wasit_qurancom":
        return f"https://quran.com/al-maidah/{v}/tafsirs/ar-tafsir-al-wasit"
    raise KeyError(source_id)


