def validate_data() -> None:
    assert set(DATA) == set(VERSES)
    for verse, record in DATA.items():
        assert all(len(record[field]) == 5 for field in ("notes", "context", "critical", "research")), verse
        assert set(record["classical"]) == SUNNI | SHIA, verse
        expected_modern = (
            {"ar_qe_arabic_moyassar", "ar_wasit_qurancom"}
            if verse in {22, 24}
            else {"ar_qe_arabic_moyassar", "en_tafheem_ul_quran"}
        )
        assert set(record["modern_sources"]) == expected_modern, verse
        assert set(record["models"]) == MODELS, verse
        for field in ("notes", "context", "critical", "research"):
            assert all(len(row["text"].split()) >= 14 and row["cite"].strip() for row in record[field]), (verse, field)


